"""Bit-identity gate for the seam boot contract (workstream 0).

Workstream 0 is purely ADDITIVE: `DDPGBCActor`, `AWRActor` and `FQLActor` gain a
`next_action_vgoal` bootstrap key they never emitted, and `Critic.BOOT_COND`
declares which key a critic reads. Nothing existing may move.

This test enumerates every critic x actor-family pair, recomputes `sample_bootstrap`
and `compute_static` at fixed seeds, and asserts every array recorded in
tests/impls/fixtures/boot_contract_reference.npz is byte-identical. The baseline was
generated by tests/impls/gen_boot_contract_fixture.py at the tip of
feat/metaworld-runs, BEFORE any actor or critic edit.

If a pair legitimately gains behaviour (density_fb x {ddpgbc, awr, fql} do), it was
absent from the baseline and so is not constrained here -- it is covered by that
task's own test. What this file forbids is a pair that used to work changing.
"""
import os

import numpy as np
import pytest

import jax

from tests.impls.gen_boot_contract_fixture import FIXTURE, collect, pair_statics


@pytest.fixture(scope="module", autouse=True)
def _require_cpu():
    """The baseline is a BYTE-identity fixture, so it is platform-specific: the same
    graph on GPU differs from CPU in the last bits and every comparison below fails
    for a reason that has nothing to do with the change under test.

    tests/impls/conftest.py imports jax before this module's setdefault can run, so
    JAX_PLATFORMS must be set on the command line. Fail loudly rather than red-herring:

        JAX_PLATFORMS=cpu PYTHONPATH=$PWD python -m pytest tests/impls/test_boot_contract.py
    """
    backend = jax.default_backend()
    if backend != "cpu":
        pytest.fail(
            f"boot-contract gate ran on {backend!r}, but the baseline fixture is CPU. "
            f"Re-run with JAX_PLATFORMS=cpu."
        )


@pytest.fixture(scope="module")
def baseline():
    if not os.path.exists(FIXTURE):
        pytest.fail(
            f"missing {FIXTURE} -- regenerate it from a tree with NO workstream-0 edits:\n"
            f"    JAX_PLATFORMS=cpu PYTHONPATH=$PWD python tests/impls/gen_boot_contract_fixture.py"
        )
    return dict(np.load(FIXTURE, allow_pickle=True))


@pytest.fixture(scope="module")
def current():
    return collect()


def test_no_previously_working_pair_regressed(baseline, current):
    """A pair recorded in the baseline must still compute."""
    missing = sorted({k for k in baseline if k != "__failed__"} - set(current))
    assert not missing, (
        f"{len(missing)} baseline array(s) can no longer be computed; "
        f"first few: {missing[:8]}"
    )


def test_every_baseline_array_is_byte_identical(baseline, current):
    """The whole point of workstream 0: it adds keys and moves nothing."""
    moved = sorted(
        k for k in baseline
        if k != "__failed__" and k in current and not np.array_equal(baseline[k], current[k])
    )
    assert not moved, f"{len(moved)} array(s) moved; first few: {moved[:8]}"


def test_flowbc_value_goal_draw_is_actually_at_the_value_goal(current):
    """Guards the discriminating property: value_goals != actor_goals in the synthetic
    batch, so the two bootstrap actions must differ. If an actor drew its 'value-goal'
    action at the actor goal, this is the assertion that catches it."""
    a = current["boot|gciql|flowbc|next_action"]
    v = current["boot|gciql|flowbc|next_action_vgoal"]
    assert not np.allclose(a, v)


def test_td_fb_reads_the_actor_goal_action_and_ignores_the_value_goal_one():
    """td_fb's critic stage is `measure_loss`. It measures 0.920 at the actor goal vs 0.076 at the value goal
    (impls/critics/td_fb.py::stage_loss). Emitting the vgoal key everywhere must not
    change which key td_fb consumes.

    Asserted behaviourally, not by grepping the source: perturb one bootstrap key at a
    time and check which one the loss responds to.
    """
    from impls.agents import Agent
    from impls.utils.config_utils import load_config
    import jax.numpy as jnp
    from tests.impls.gen_boot_contract_fixture import make_batch, B, OBS, ACT

    cfg = load_config("td_fb", "flowbc", "cube_single")
    cfg["batch_size"] = B
    agent = Agent.create("td_fb", "flowbc", 0, jnp.zeros((B, OBS)), jnp.zeros((B, ACT)), cfg)
    batch = make_batch()
    cond = agent.critic.sample_cond(agent.net, batch, jax.random.PRNGKey(0))
    boot = agent.actor.sample_bootstrap(agent.net, batch, cond, jax.random.PRNGKey(1))
    assert "next_action_vgoal" in boot, "flowbc should emit the value-goal draw for td_fb's cond"

    def loss_with(b):
        return float(jnp.asarray(agent.compute_static(batch, cond, b)["measure_loss"]).mean())

    base = loss_with(boot)
    junk = jnp.zeros_like(boot["next_action"])
    assert loss_with({**boot, "next_action_vgoal": junk}) == base, \
        "td_fb must IGNORE boot['next_action_vgoal'] -- reading it is the 0.920 -> 0.076 cliff"
    assert loss_with({**boot, "next_action": junk}) != base, \
        "td_fb must READ boot['next_action']"
