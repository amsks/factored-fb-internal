"""Generate PAPER/ICLR/table_objcoords.tex — the OBJECT-COORDINATE column of every family.

Rows = datasets, columns = algorithms, in the layout of `PAPER/ICLR/table.tex` (tab:main),
so the two read the same way. Each family appears as a matched pair: the vanilla estimator
and the same estimator with the density (normalized categorical) objective, both with the
backward tower / feature map reading the eps-scaled object-coordinate block.

WHY A GENERATOR. `table_privcoord.tex` is hand-maintained, and its cells go stale the moment
another seed lands. This reads the runs off disk, so refreshing after a campaign is one
command rather than 30 hand-edited cells and their seed superscripts.

ONLY FINISHED RUNS COUNT. A cell is built from seeds that have `params_500000.pkl` AND an
eval row at step 500000. That matters while a seed campaign is in flight: a run sitting at
120k has an eval.csv whose last row would otherwise be silently averaged in as if it were a
final number.

PROTOCOL, and it is not tab:main's. These are the training loop's own evals -- 20 episodes
per task, mean over the environment's 5 tasks, goal-conditioned (z = project_z(B(goal))).
tab:main quotes 50 episodes. The two are not interchangeable, which is why the caption says
so and why the seed count is printed on every cell.
"""
import argparse
import collections
import pathlib
import re

import numpy as np
import pandas as pd

FINAL = 500_000

# (column header, critic) -- the object-coordinate arm of each family.
COLUMNS = [
    ("FB",           "fb_oc"),
    ("Density-FB",   "density_fb"),
    ("RLDP",         "rldp_oc"),
    ("Density-RLDP", "rldp_density_oc"),
    ("HILP",         "hilp_oc"),
    ("Density-HILP", "hilp_density_oc"),
]
ROWS = [("cube-single", "cube-single-play-v0"), ("cube-double", "cube-double-play-v0")]


def per_seed_final(exp: pathlib.Path, env: str, critic: str) -> dict:
    """seed -> final-step success (mean over the env's eval tasks), finished runs only."""
    out = {}
    for d in exp.glob(f"{env}_{critic}_flowbc_seed_*"):
        m = re.match(rf"{re.escape(env)}_{re.escape(critic)}_flowbc_seed_(\d+)$", d.name)
        if not m or not (d / f"params_{FINAL}.pkl").exists():
            continue
        f = d / "eval.csv"
        if not f.exists():
            continue
        df = pd.read_csv(f)
        sub = df[df["step"] == FINAL]
        if len(sub):
            out[int(m.group(1))] = float(sub["success"].mean())
    return out


def cell(vals: dict) -> tuple:
    """(latex, mean or nan). '---' when a cell was never run."""
    if not vals:
        return "---", float("nan")
    a = np.array([vals[s] for s in sorted(vals)])
    n = len(a)
    body = f"{a.mean():.3f}" if n == 1 else f"{a.mean():.3f}\\pm{a.std(ddof=1):.3f}"
    return f"${body}^{{\\,{n}}}$", float(a.mean())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--exp-root", default="exp")
    ap.add_argument("--out", default="PAPER/ICLR/table_objcoords.tex")
    args = ap.parse_args()
    exp = pathlib.Path(args.exp_root)

    grid, means = {}, {}
    for label, env in ROWS:
        for head, critic in COLUMNS:
            tex, mu = cell(per_seed_final(exp, env, critic))
            grid[(label, head)], means[(label, head)] = tex, mu

    L = [r"\documentclass[10pt]{article}",
         r"\usepackage[margin=0.7in]{geometry}",
         r"\usepackage{booktabs}", r"\usepackage{amsmath}",
         r"\usepackage{graphicx}", r"\usepackage{multirow}",
         r"\pagestyle{empty}", r"\begin{document}", "",
         r"% ---- Object-coordinate arms, every family, vanilla vs the density objective. ----",
         r"% Auto-generated by scripts/make_table_objcoords.py -- do not edit by hand.",
         f"% Regenerate: .venv-jax/bin/python scripts/make_table_objcoords.py",
         r"\begin{table}[h]\centering",
         r"\caption{\textbf{Privileged object coordinates, every estimator family.} The"
         r" backward tower ($B$ for FB/RLDP, $\phi$ for HILP) consumes the"
         r" $\epsilon$-scaled object-coordinate block --- 3 numbers (cube $xyz$) on"
         r" \texttt{cube-single}, 6 on \texttt{cube-double} --- while the forward map, the"
         r" left encoder and the policy keep the whole observation. Each family is a matched"
         r" pair: the vanilla estimator and the same estimator trained with the normalized"
         r" categorical (density) objective. Superscripts give the number of seeds; mean"
         r" $\pm$ sd, and $n{=}1$ cells should not be quoted. \emph{Protocol:} 500k gradient"
         r" steps, flow (FQL+BC) actor, 20 eval episodes per task, mean over the"
         r" environment's 5 evaluation tasks --- NOT the 50-episode protocol of"
         r" Table~\ref{tab:main}.}",
         r"\label{tab:objcoords}",
         r"\setlength{\tabcolsep}{5pt}",
         r"\resizebox{\textwidth}{!}{%",
         r"\begin{tabular}{l cc cc cc}",
         r"\toprule",
         r"& \multicolumn{2}{c}{FB} & \multicolumn{2}{c}{RLDP} & \multicolumn{2}{c}{HILP} \\",
         r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
         r"Dataset & vanilla & + density & vanilla & + density & vanilla & + density \\",
         r"\midrule",
         r"\multicolumn{7}{l}{\emph{OGBench}, object-coordinate backward map}\\"]

    for label, _env in ROWS:
        vals = {h: means[(label, h)] for h, _ in COLUMNS}
        best = max((v for v in vals.values() if not np.isnan(v)), default=None)
        cells = []
        for head, _ in COLUMNS:
            t = grid[(label, head)]
            if best is not None and not np.isnan(vals[head]) and vals[head] >= best - 1e-12:
                t = t.replace("$", r"$\mathbf{", 1)[:-1] + "}$" if t != "---" else t
            cells.append(t)
        L.append(f"\\texttt{{{label}}} & " + " & ".join(cells) + r" \\")

    L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", r"\end{document}"]
    out = pathlib.Path(args.out)
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}")
    for label, _ in ROWS:
        print(f"  {label:<14}" + "  ".join(f"{h}={grid[(label,h)]}" for h, _ in COLUMNS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
