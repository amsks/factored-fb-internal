"""Generate PAPER/fb-gciql-bridge/config-matrix-gciql.md: per-config delta vs the d50 base."""
import glob, os, yaml

BASE = "configs/gciql/cube_single_state_gciql_flow_bilinear_d50.yaml"
# bridge-relevant = gciql/gciql_flow/isfb agents; hiql/gcivl/crl/tdmpc = other track/methods
SKIP = ("hiql", "gcivl", "crl", "tdmpc")
# housekeeping keys not worth showing
NOISE = {"seed", "exp_name", "restore_path", "restore_epoch", "wandb_mode",
         "log_interval", "save_interval", "eval_on_cpu", "defaults", "run_group"}

def flat(d, pre=""):
    out = {}
    for k, v in (d or {}).items():
        kk = f"{pre}{k}"
        if isinstance(v, dict):
            out.update(flat(v, kk + "."))
        else:
            out[kk] = v
    return out

base = flat(yaml.safe_load(open(BASE)))

rows = []
for f in sorted(glob.glob("configs/gciql/*.yaml")):
    name = os.path.basename(f)
    if any(s in name for s in SKIP) or f == BASE:
        continue
    cfg = flat(yaml.safe_load(open(f)))
    grp = cfg.get("run_group", "?")
    deltas = []
    for k in sorted(set(base) | set(cfg)):
        if k in NOISE:
            continue
        b, c = base.get(k, "<unset>"), cfg.get(k, "<unset>")
        if b != c:
            if b == "<unset>":
                deltas.append(f"+`{k}={c}`")
            elif c == "<unset>":
                deltas.append(f"-`{k}` (was {b})")
            else:
                deltas.append(f"`{k}`: {b} -> {c}")
    rows.append((name, grp, deltas))

out = open("PAPER/fb-gciql-bridge/config-matrix-gciql.md", "w")
out.write(f"""# GCIQL config matrix — deltas vs the base cell

**Base = `{BASE}`** (`run_group: GCIQL-State-Flow-Bilinear-d50`):
cube-single-play state, `gciql_flow` agent (IQL bilinear critic + FQL flow actor),
`value_arch=bilinear`, `value_latent_dim=50`, `bc_coeff=3.0`, exact goal, 1M steps.

Each row lists ONLY what that config changes/adds relative to this base
(housekeeping keys — seed, log/save intervals, wandb_mode, eval_on_cpu — omitted).
HIQL/GCIVL/CRL configs are the SOTA track and excluded.

Auto-generated by scripts/gen_config_matrix.py; regenerate after adding cells.

| config | wandb group | delta vs base |
|---|---|---|
""")
for name, grp, deltas in rows:
    out.write(f"| `{name}` | {grp} | {'; '.join(deltas) if deltas else '(identical)'} |\n")
out.close()
print(f"wrote {len(rows)} rows")
