"""campaign/gen_native.py — generate per-(dataset, native-agent) Hydra domain configs
and emit the native job list (fb, fb_flowbc x 19 datasets x 3 seeds = 114 jobs).

    <fb>/.venv/bin/python campaign/gen_native.py
      -> configs/domain/camp/<slug>__<agent>.yaml
      -> campaign/jobs_native.txt   (one train.py command per line, no GPU pinning)
"""
import os
from pathlib import Path

from registry import DATASETS, NATIVE_AGENTS, SEEDS, NUM_TRAIN_STEPS, SAVE_EVERY, CAMPAIGN_OUT

FB_ROOT = Path(__file__).resolve().parent.parent
CONF_DIR = FB_ROOT / "configs" / "domain" / "camp"
JOBS = FB_ROOT / "campaign" / "jobs_native.txt"

CONFIG_TMPL = """# @package _global_
# generated by campaign/gen_native.py — do not edit by hand
defaults:
  - /agent: {agent}
  - _self_
domain: {domain}
data_format: {data_format}
build_env: false
data_path: {data_path}
bc_coeff: {bc_coeff}
"""


def main():
    CONF_DIR.mkdir(parents=True, exist_ok=True)
    lines = []
    for ds in DATASETS:
        for aname, a in NATIVE_AGENTS.items():
            cfg_name = f"{ds['slug']}__{aname}"
            (CONF_DIR / f"{cfg_name}.yaml").write_text(CONFIG_TMPL.format(
                agent=a["agent"], domain=ds["domain"], data_format=ds["data_format"],
                data_path=ds["data_path"], bc_coeff=a["bc_coeff"]))
            for s in SEEDS:
                run_dir = f"{CAMPAIGN_OUT}/native/{aname}__{ds['slug']}__s{s}"
                cmd = (
                    f".venv/bin/python train.py domain=camp/{cfg_name} seed={s} "
                    f"num_train_steps={NUM_TRAIN_STEPS} save_every={SAVE_EVERY} "
                    f"eval_every=0 log_every=2000 use_wandb=false "
                    f"hydra.run.dir={run_dir}"
                )
                lines.append(cmd)
    JOBS.write_text("\n".join(lines) + "\n")
    print(f"[gen_native] wrote {len(list(CONF_DIR.glob('*.yaml')))} configs -> {CONF_DIR}")
    print(f"[gen_native] wrote {len(lines)} jobs -> {JOBS}")
    print(f"[gen_native]   {len(DATASETS)} datasets x {len(NATIVE_AGENTS)} agents x {len(SEEDS)} seeds")


if __name__ == "__main__":
    main()
